class TestQueueModel(BaseBackendTest):
    def test_active_and_pending_counts(self):
        queue = self.make_queue()
        self.make_ticket(queue=queue, code="A1", status="active", position=0)
        self.make_ticket(queue=queue, code="A2", status="pending", position=1)
        self.make_ticket(queue=queue, code="A3", status="pending", position=2)
        self.assertEqual(queue.active_count(), 1)
        self.assertEqual(queue.pending_count(), 2)

    def test_to_dict_builds_join_url_from_base(self):
        queue = self.make_queue(name="Pharmacy", code="PHA")
        d = queue.to_dict(base_url="http://testhost")
        self.assertEqual(d["name"], "Pharmacy")
        self.assertTrue(d["join_url"].startswith("http://testhost/join/"))
        self.assertIn(queue.join_token, d["join_url"])

    def test_join_token_autogenerated_and_unique(self):
        q1 = self.make_queue(code="Q1")
        q2 = self.make_queue(service=q1.service, name="Other", code="Q2")
        self.assertIsNotNone(q1.join_token)
        self.assertNotEqual(q1.join_token, q2.join_token)


class TestTicketModel(BaseBackendTest):
    def test_status_predicates(self):
        t = self.make_ticket(status="active")
        self.assertTrue(t.is_active())
        self.assertFalse(t.is_pending())

    def test_actual_wait_minutes_computed(self):
        issued = datetime(2024, 1, 1, 10, 0, 0)
        called = datetime(2024, 1, 1, 10, 7, 0)
        t = self.make_ticket(issued_at=issued, called_at=called)
        self.assertEqual(t.actual_wait_minutes(), 7)

    def test_actual_wait_minutes_none_without_called_at(self):
        t = self.make_ticket(issued_at=datetime.utcnow(), called_at=None)
        self.assertIsNone(t.actual_wait_minutes())

    def test_actual_wait_never_negative(self):
        issued = datetime(2024, 1, 1, 10, 7, 0)
        called = datetime(2024, 1, 1, 10, 0, 0)  # called "before" issued
        t = self.make_ticket(issued_at=issued, called_at=called)
        self.assertEqual(t.actual_wait_minutes(), 0)

    def test_to_dict_serializes_datetimes_iso(self):
        t = self.make_ticket(code="GEN-009")
        d = t.to_dict()
        self.assertEqual(d["code"], "GEN-009")
        self.assertEqual(d["status"], "pending")
        self.assertIsInstance(d["issued_at"], str)  # isoformat
        self.assertIsNone(d["called_at"])


class TestInviteTokenModel(BaseBackendTest):
    def _invite(self, *, used=False, expires_in_hours=1):
        svc = self.make_service()
        inv = InviteToken(
            service_id=svc.id,
            admin_role="agent",
            used=used,
            expires_at=datetime.utcnow() + timedelta(hours=expires_in_hours),
        )
        self.db.session.add(inv)
        self.db.session.commit()
        return inv

    def test_valid_when_unused_and_unexpired(self):
        inv = self._invite(used=False, expires_in_hours=1)
        self.assertTrue(inv.is_valid())

    def test_invalid_when_expired(self):
        inv = self._invite(used=False, expires_in_hours=-1)
        self.assertTrue(inv.is_expired())
        self.assertFalse(inv.is_valid())

    def test_consume_marks_used_and_invalidates(self):
        inv = self._invite()
        inv.consume()
        self.assertTrue(inv.used)
        self.assertFalse(inv.is_valid())

    def test_to_dict_builds_invite_url(self):
        inv = self._invite()
        d = inv.to_dict(base_url="http://testhost")
        self.assertTrue(d["invite_url"].endswith(inv.token))


