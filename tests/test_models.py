"""
Unit tests for models.py — the behavioural methods on each model
(predicates, to_dict shapes, expiry logic, computed counts/waits).

Persistence is exercised through the in-memory SQLite bound by BaseBackendTest,
but most assertions target pure Python behaviour on the model objects.
"""
from datetime import datetime, timedelta, timezone, date

from tests.base import BaseBackendTest
from models import (
    User, PendingRegistration, ResetCode, Service, Admin, Queue, Ticket,
    InviteToken, ServiceSchedule, Notification, DeviceToken, SwapRequest,
)


class TestUserModel(BaseBackendTest):
    def test_role_predicates(self):
        client = self.make_user(role="client")
        self.assertTrue(client.is_client())
        self.assertFalse(client.is_admin())

    def test_mark_verified_flips_flag(self):
        user = self.make_user(verified=False)
        self.assertFalse(user.is_verified())
        user.mark_verified()
        self.assertTrue(user.is_verified())

    def test_to_dict_shape_and_string_ids(self):
        user = self.make_user(username="bob", email="bob@x.com", role="admin")
        d = user.to_dict()
        self.assertEqual(
            set(d), {"user_id", "username", "email", "role"}
        )
        self.assertEqual(d["user_id"], str(user.id))
        self.assertEqual(d["role"], "admin")


class TestPendingRegistrationModel(BaseBackendTest):
    def _make_pending(self, expire_at):
        rec = PendingRegistration(
            username="alice", email="a@x.com", hashed_password=b"h",
            role="client", code="123456", expire_at=expire_at,
        )
        self.db.session.add(rec)
        self.db.session.commit()
        return rec

    def test_is_expired_true_in_past(self):
        rec = self._make_pending(datetime.utcnow() - timedelta(minutes=1))
        self.assertTrue(rec.is_expired())

    def test_is_expired_false_in_future(self):
        rec = self._make_pending(datetime.utcnow() + timedelta(minutes=10))
        self.assertFalse(rec.is_expired())

    def test_update_code_replaces_code_and_expiry(self):
        rec = self._make_pending(datetime.utcnow() + timedelta(minutes=10))
        new_exp = datetime.utcnow() + timedelta(minutes=30)
        rec.update_code("654321", new_exp)
        self.assertEqual(rec.code, "654321")
        self.assertEqual(rec.expire_at, new_exp)

    def test_to_user_payload_carries_credentials(self):
        rec = self._make_pending(datetime.utcnow() + timedelta(minutes=10))
        payload = rec.to_user_payload()
        self.assertEqual(payload["email"], "a@x.com")
        self.assertEqual(payload["hashed_password"], b"h")


class TestResetCodeModel(BaseBackendTest):
    def test_is_expired_and_update(self):
        rec = ResetCode(email="a@x.com", code="111111",
                        expire_at=datetime.utcnow() - timedelta(seconds=1))
        self.db.session.add(rec)
        self.db.session.commit()
        self.assertTrue(rec.is_expired())
        future = datetime.utcnow() + timedelta(minutes=5)
        rec.update_code("222222", future)
        self.assertEqual(rec.code, "222222")
        self.assertFalse(rec.is_expired())


