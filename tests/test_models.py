class TestSwapRequestModel(BaseBackendTest):
    def test_status_constants_and_predicates(self):
        self.assertEqual(SwapRequest.STATUS_PENDING, "pending")
        svc = self.make_service()
        q = self.make_queue(service=svc)
        t1 = self.make_ticket(queue=q, code="S1", position=1)
        t2 = self.make_ticket(queue=q, code="S2", position=2)
        swap = SwapRequest(service_id=svc.id,
                           requester_ticket_id=t1.id,
                           target_ticket_id=t2.id)
        self.db.session.add(swap)
        self.db.session.commit()
        self.assertTrue(swap.is_pending())
        self.assertFalse(swap.is_accepted())
        swap.status = SwapRequest.STATUS_ACCEPTED
        self.assertTrue(swap.is_accepted())

    def test_to_dict_shape(self):
        svc = self.make_service()
        q = self.make_queue(service=svc)
        t1 = self.make_ticket(queue=q, code="S1", position=1)
        t2 = self.make_ticket(queue=q, code="S2", position=2)
        swap = SwapRequest(service_id=svc.id,
                           requester_ticket_id=t1.id, target_ticket_id=t2.id)
        self.db.session.add(swap)
        self.db.session.commit()
        d = swap.to_dict()
        self.assertEqual(d["status"], "pending")
        self.assertEqual(d["requester_ticket_id"], str(t1.id))
        self.assertIsNone(d["responded_at"])
